/** The usage text with the pending branches' lines, as the skills see the CLI. */
export const combinedUsage = (): string => `${USAGE}\n${PENDING.flatMap((p) => p.usage).join("\n")}\n`

export function renderReference(): string {
  const pending = PENDING.map((p) => `From \`${p.branch}\`:\n\n\`\`\`text\n${p.usage.join("\n")}\n\`\`\``).join("\n\n")
  return [
    "# winvm commands",
    "",
    "Generated by `bun scripts/skills.ts` from winvm's own usage text (`winvm help`).",
    "Don't edit it by hand. Every command takes `-i NAME`; see the winvm skill.",
    "",
    "```text",
    USAGE.trimEnd(),
    "```",
    "",
    "## Shipping alongside (not merged yet)",
    "",
    pending,
    "",
  ].join("\n")
}

/** Folders under skills/ that hold a SKILL.md. */
export const skillNames = (): string[] =>
  readdirSync(SKILLS, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(resolve(SKILLS, e.name, "SKILL.md")))
    .map((e) => e.name)
    .sort()

/** Every file under skills/, relative to it. */
export const skillFiles = (): string[] =>
  readdirSync(SKILLS, { recursive: true, encoding: "utf8" }).filter((f) => !f.endsWith(".DS_Store") && statSync(resolve(SKILLS, f)).isFile())

/** YAML frontmatter as flat key: value pairs (the skills use no nesting). */
export function frontmatter(text: string): Record<string, string> | null {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text)
  if (m === null) return null
  const out: Record<string, string> = {}
  for (const line of (m[1] ?? "").split("\n")) {
    const kv = /^([a-z-]+):\s*(.*)$/.exec(line)
    if (kv !== null) out[kv[1] ?? ""] = kv[2] ?? ""
  }
  return out
}

/** Shell-like words: whitespace splits; '...' and "..." group. */
export function words(line: string): string[] {
  const out: string[] = []
  let cur = ""
  let inWord = false
  let q: string | null = null
  for (const ch of line) {
    if (q !== null) {
      if (ch === q) q = null
      else cur += ch
      continue
    }
    if (ch === "'" || ch === '"') {
      q = ch
      inWord = true
      continue
    }
    if (/\s/.test(ch)) {
      if (inWord) out.push(cur)
      cur = ""
      inWord = false
      continue
    }
    cur += ch
    inWord = true
  }
  if (inWord) out.push(cur)
  return out
}

/** The `winvm ...` command lines in a Markdown or YAML file: fenced lines, inline code, and `run:` lines. */
export function commandLines(text: string): string[] {
  const out: string[] = []
  const take = (s: string): void => {
    // [--a|--b] alternatives are not pipes; drop the brackets.
    const flat = s.replace(/\[([^\]]*)\]/g, (_m, inner: string) => ` ${inner.replaceAll("|", " ")} `)
    for (const seg of flat.split(/&&|\|\||;|\s\|\s/)) {
      const t = seg.replace(/\s#\s.*$/, "").trim().replace(/^\$\s+/, "")
      if (/^winvm\s/.test(t)) out.push(t)
    }
  }
  let fenced = false
  for (const line of text.split("\n")) {
    if (/^\s*```/.test(line)) {
      fenced = !fenced
      continue
    }
    if (fenced) take(line)
    else for (const m of line.matchAll(/`([^`]+)`/g)) take(m[1] ?? "")
    const hash = /^\s*#\s+(winvm\s.*)$/.exec(line)
    if (!fenced && hash !== null) take(hash[1] ?? "")
  }
  return out
}

if (import.meta.main) {
  const want = renderReference()
  const have = existsSync(REFERENCE) ? readFileSync(REFERENCE, "utf8") : ""
  if (process.argv.includes("--check")) {
    if (have !== want) {
      console.error(`${REFERENCE} is stale: run \`bun scripts/skills.ts\``)
      process.exit(1)
    }
    process.exit(0)
  }
  if (have !== want) {
    writeFileSync(REFERENCE, want)
    console.log(`wrote ${REFERENCE}`)
  } else console.log(`${REFERENCE} is current`)
}
